-- total waste generated by each state
SELECT
    State,
    ROUND(SUM(Daily_Waste_Generation_Tons),2)
        AS Total_Waste_Generation
FROM wsql
GROUP BY State
ORDER BY Total_Waste_Generation DESC;
-- top 10 cities generating waste
SELECT
    City,
    State,
    ROUND(SUM(Daily_Waste_Generation_Tons),2)
        AS Total_Waste
FROM wsql
GROUP BY City, State
ORDER BY Total_Waste DESC
LIMIT 10;
-- waste generation by waste type
SELECT
    Waste_Type,
    ROUND(SUM(Daily_Waste_Generation_Tons),2)
        AS Total_Waste
FROM wsql
GROUP BY Waste_Type
ORDER BY Total_Waste DESC;
-- monthly waste generation trend
SELECT
    Year,
    Month,
    ROUND(SUM(Daily_Waste_Generation_Tons),2)
        AS Total_Waste
FROM wsql
GROUP BY Year, Month
ORDER BY Year, Month;
-- avg collection efficiency by state
SELECT
    State,
    ROUND(AVG(Collection_Efficiency_Percentage),2)
        AS Average_Collection_Efficiency
FROM wsql
GROUP BY State
ORDER BY Average_Collection_Efficiency DESC;
-- cities with low collection efficiencies
SELECT
    City,
    State,
    ROUND(AVG(Collection_Efficiency_Percentage),2)
        AS Collection_Efficiency
FROM wsql
GROUP BY City, State
HAVING AVG(Collection_Efficiency_Percentage) < 50
ORDER BY Collection_Efficiency;
-- waste segregation analysis
SELECT
    State,
    ROUND(AVG(Waste_Segregation_Rate),2)
        AS Average_Segregation_Rate
FROM wsql
GROUP BY State
ORDER BY Average_Segregation_Rate DESC;
-- recycling rate by waste type
SELECT
    Waste_Type,
    ROUND(AVG(Recycling_Rate),2) AS Average_Recycling_Rate
FROM wsql
GROUP BY Waste_Type
ORDER BY Average_Recycling_Rate DESC;
-- treatment method distribution
SELECT
    Treatment_Method,
    COUNT(*) AS Total_Records
FROM wsql
GROUP BY Treatment_Method
ORDER BY Total_Records DESC;
-- composting rate by state
SELECT
    State,
    ROUND(AVG(Composting_Rate),2) AS Average_Composting_Rate
FROM wsql
GROUP BY State
ORDER BY Average_Composting_Rate DESC;
-- landfill dependency by state
SELECT
    City,
    State,
    ROUND(AVG(Landfill_Dependency_Rate),2)
        AS Landfill_Dependency
FROM wsql
GROUP BY City, State
ORDER BY Landfill_Dependency DESC
LIMIT 10;
-- total waste management by state
SELECT
    State,
    SUM(Waste_Management_Budget_INR) AS Total_Budget
FROM wsql
GROUP BY State
ORDER BY Total_Budget DESC;
-- avg cost per ton by city
SELECT
    City,
    State,
    ROUND(AVG(Cost_Per_Ton_INR),2) AS Average_Cost_Per_Ton
FROM wsql
GROUP BY City, State
ORDER BY Average_Cost_Per_Ton DESC;
-- budget and waste generation comparison
SELECT
    State,
    SUM(Waste_Management_Budget_INR) AS Total_Budget,
    ROUND(SUM(Daily_Waste_Generation_Tons),2) AS Total_Waste
FROM wsql
GROUP BY State
ORDER BY Total_Budget DESC;
-- carbon emission by state
SELECT
    State,
    ROUND(SUM(Carbon_Emission_From_Waste),2)
        AS Total_Carbon_Emission
FROM wsql
GROUP BY State
ORDER BY Total_Carbon_Emission DESC;
-- Average air quality index by state
SELECT
    State,
    ROUND(AVG(Air_Quality_Index),2) AS Average_AQI
FROM wsql
GROUP BY State
ORDER BY Average_AQI DESC;
-- Sustainability category distribution
SELECT
    Sustainability_Category,
    COUNT(*) AS Total_Records
FROM wsql
GROUP BY Sustainability_Category
ORDER BY Total_Records DESC;
-- cities with the highest sustainability index
SELECT
    City,
    State,
    ROUND(AVG(Sustainability_Index),2)
        AS Average_Sustainability
FROM wsql
GROUP BY City, State
ORDER BY Average_Sustainability DESC
LIMIT 10;

